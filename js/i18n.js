  function t(key, vars) {
    const pack = DICT[cur] || DICT.vi;
    let str = pack[key] != null ? pack[key] : DICT.vi[key] != null ? DICT.vi[key] : key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), String(vars[k]));
      });
    }
    return str;
  }

  function setLang(code) {
    if (!DICT[code]) return;
    cur = code;
    document.documentElement.lang = cur;
    try { localStorage.setItem(KEY, cur); } catch (e) { /* bỏ qua */ }
  }

